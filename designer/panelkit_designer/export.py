"""Convert project data into ordinary PanelKit C++ and Arduino sketch files."""

from dataclasses import dataclass
from importlib.resources import files
from pathlib import Path
import re

from PIL import Image, ImageOps

from .catalog import WIDGETS
from .project import atomic_text, check, validate, values

HEADER = "PanelKitGenerated.h"
SOURCE = "PanelKitGenerated.cpp"
FONT = "PanelKitFont.h"
ASSETS = "PanelKitImages.h"
GENERATED = "// Generated by PanelKit Designer. Changes here are replaced on export.\n"
DEFAULT_FONT = "font_inter_regular_16::Font"


def cpp(value):
    if type(value) is bool:
        return "true" if value else "false"
    if type(value) is float:
        return repr(value) + "f"
    if isinstance(value, str):
        quoted = []
        for byte in value.encode("utf-8"):
            if byte in (34, 92, 63):
                quoted.append("\\" + chr(byte))
            elif 32 <= byte < 127:
                quoted.append(chr(byte))
            else:
                quoted.append(f"\\{byte:03o}")
        return '"' + "".join(quoted) + '"'
    if isinstance(value, list):
        return ", ".join(map(cpp, value))
    return str(value)


def rgb(value):
    return "RGB565(" + ", ".join(str(int(value[i:i+2], 16)) for i in (1, 3, 5)) + ")"


def theme_lines(data, target):
    lines = []
    for key, value in data.items():
        if key == "font_filter":
            lines.append(f"{target}.fontFilter = BitmapFilter::{value};")
        elif key == "text_height":
            lines.append(f"{target}.textHeight = {value};")
        else:
            lines.append(f"{target}.{key} = {rgb(value) if isinstance(value, str) else value};")
    return lines


def block(lines, spaces=4):
    indent = " " * spaces
    return "\n".join(indent + line if line else "" for line in lines)


@dataclass
class Raster:
    name: str
    width: int
    height: int
    words: list[int]
    mask: list[bool]

    def code(self):
        for name, type_name, data, fmt in (
            (self.name, "uint16_t", self.words, lambda n: f"0x{n:04x}"),
            (self.name + "_mask", "bool", self.mask, lambda n: "1" if n else "0"),
        ):
            if not data:
                continue
            yield f"static const {type_name} {name}[] PROGMEM = {{"
            for offset in range(0, len(data), 16):
                yield "    " + ", ".join(map(fmt, data[offset:offset+16])) + ","
            yield "};"


def load_raster(path, name):
    with Image.open(path) as opened:
        check(opened.width * opened.height <= 1048576,
              f"{path.name}: resize the source to at most 1,048,576 pixels before import.")
        image = ImageOps.exif_transpose(opened).convert("RGBA")
    words, mask = [], []
    rgba = iter(image.tobytes())
    for r, g, b, a in zip(rgba, rgba, rgba, rgba):
        words.append(((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3))
        mask.append(a >= 128)
    return Raster(name, image.width, image.height, words, [] if all(mask) else mask)


class Exporter:
    def __init__(self, project):
        validate(project)
        self.project = project
        self.widgets = project.ordered()
        self.rasters = {}
        self.widget_images = {}
        self.declarations, self.definitions = [], []
        self.data, self.callbacks, self.setup, self.layout, self.frame = [], [], [], [], []
        self.tabs, self.windows = [], []
        self.atlases = {}
        self.font = project.font_symbol or DEFAULT_FONT
        for widget in self.widgets:
            props = values(widget)
            if props.get("image"):
                src = project.asset(props["image"])
                if src not in self.rasters:
                    self.rasters[src] = load_raster(src, f"pixels_{len(self.rasters)}")
                self.widget_images[widget.name] = self.rasters[src]
        self.root_type = f"Panel<{project.width}, {project.height}, {cpp(project.buffered)}>"
        self.setup.extend(["screen.activate();", f"screen.setBackground({rgb(project.background)});",
                           "PanelTheme baseTheme;", f"baseTheme.font = &{self.font};"])
        self.setup.extend(theme_lines(project.theme, "baseTheme"))

    def add_widgets(self):
        for index, widget in enumerate(self.widgets):
            kind = widget.kind
            schema = WIDGETS[kind]
            props = values(widget)
            obj = f"widgets::{widget.name}"
            tag = f"item_{index}"
            parent = f"&widgets::{widget.parent}" if widget.parent else "&screen"
            size = f"{widget.width}, {widget.height}"
            args = parent
            type_name = schema.cpp
            image = self.widget_images.get(widget.name)
            if kind == "Sprite":
                aw, ah = (image.width, image.height) if image else (1, 1)
                region = props["region"] or [0, 0, aw, ah]
                check(region[0] + region[2] <= aw and region[1] + region[3] <= ah,
                      f"{widget.name}: sprite region exceeds the image.")
                key = image.name if image else ""
                if key not in self.atlases:
                    atlas = f"atlas_{len(self.atlases)}"
                    self.data.append(f"static Pixmap<{aw}, {ah}> {atlas};")
                    self.atlases[key] = atlas
                    if image:
                        self.setup.extend(self.load_pixmap(atlas, image))
                atlas = self.atlases[key]
                type_name += f"<{size}, {aw}, {ah}>"
                args = f"{atlas}, {{{cpp(region)}}}, {parent}"
            elif kind in ("Panel", "Button", "Plot"):
                samples = f"{props['capacity']}, " if kind == "Plot" else ""
                type_name += f"<{size}, {samples}{cpp(props['buffered'])}>"
            elif schema.direct and not schema.container:
                args = f"{size}, {parent}"
            else:
                type_name += f"<{size}>"
            self.declarations.append(f"extern {type_name} {widget.name};")
            self.definitions.append(f"{type_name} {widget.name}({args});")
            self.setup.extend([f"{obj}.setName({cpp(widget.name)});",
                               f"{obj}.setLoc({widget.x}, {widget.y});",
                               f"{obj}.setOrder({widget.order});"])
            if widget.active:
                self.setup.append(f"{obj}.activate();")
            if not widget.visible:
                self.setup.append(f"{obj}.setVisible(false);")
            self.configure_widget(widget, props, obj, tag, image)
            for event, signature in schema.events.items():
                if event in widget.events:
                    function = f"{tag}_{event}"
                    self.callbacks.append(f"static void {function}({signature})\n{{\n"
                                          f"{block(widget.events[event].splitlines())}\n}}")
                    self.setup.append(f"{obj}.{event}({function});")

    @staticmethod
    def load_pixmap(target, image):
        lines = [f"for (int y = 0; y < {image.height}; ++y)", "{",
                 f"    for (int x = 0; x < {image.width}; ++x)", "    {",
                 f"        const size_t i = size_t(y) * {image.width} + x;"]
        guard = f"if (pgm_read_byte({image.name}_mask + i)) " if image.mask else ""
        lines += [f"        {guard}{target}.setPixelValue(x, y, pgm_read_word({image.name} + i));",
                  "    }", "}"]
        return lines

    def configure_widget(self, widget, p, obj, tag, image):
        kind = widget.kind
        schema = WIDGETS[kind]
        if "theme" in p:
            lines = theme_lines(p["theme"], "theme")
            if lines:
                self.setup.extend(["{", "    PanelTheme theme = baseTheme;",
                                  *["    " + line for line in lines],
                                  f"    {obj}.setTheme(theme);", "}"])
            else:
                self.setup.append(f"{obj}.setTheme(baseTheme);")
        if kind in ("Label", "Button", "List"):
            size_key = {"Label": "font_height", "Button": "font_scale", "List": "row_height"}[kind]
            self.setup.append(f"{obj}.setFont({self.font}, {cpp(p[size_key])});")
        if kind == "Button":
            self.setup.append(f"{obj}.setJustification(TextJustify::{p['justify']}, "
                              f"TextVAlign::{p['vertical_align']});")
        if p.get("items"):
            self.data.append(f"static const char* const {tag}_items[] = {{{cpp(p['items'])}}};")
            self.setup.append(f"{obj}.setItems({tag}_items, {len(p['items'])});")
        if kind == "Tabs" and p["pages"]:
            captions, names = zip(*p["pages"])
            self.data.extend([f"static const char* const {tag}_labels[] = {{{cpp(list(captions))}}};",
                              f"static BaseComponent* const {tag}_pages[] = {{"
                              + ", ".join(f"&widgets::{name}" for name in names) + "};"])
            self.tabs.extend([f"{obj}.setPages({tag}_labels, {tag}_pages, {len(names)});",
                              f"{obj}.setCurrent({p['selected']});"])
        if kind == "Table" and p["columns"]:
            columns = ", ".join("{" + cpp(column) + "}" for column in p["columns"])
            count = len(p["columns"])
            self.data.append(f"static const PanelTable::Column {tag}_columns[] = {{{columns}}};")
            if p["rows"]:
                rows = ",\n    ".join("{" + cpp(row) + "}" for row in p["rows"])
                self.data.append(f"static const char* const {tag}_rows[][{count}] = {{\n    {rows}\n}};")
                self.callbacks.append(f"static const char* {tag}_read(void*, int row, int col)\n"
                                      f"{{\n    return {tag}_rows[row][col];\n}}")
            reader = f"{tag}_read" if p["rows"] else "nullptr"
            self.setup.append(f"{obj}.setModel({tag}_columns, {count}, {len(p['rows'])}, {reader});")
        if kind == "Flex":
            entries = p["layout"] or [[child.name, 0, 1] for child in self.widgets
                                       if child.parent == widget.name]
            if entries:
                items = ", ".join(f"{{&widgets::{name}, {basis}, {weight}}}"
                                  for name, basis, weight in entries)
                self.data.append(f"static const PanelFlexItem {tag}_layout[] = {{{items}}};")
                self.layout.append(f"{obj}.setLayout({tag}_layout, {len(entries)}, "
                                   f"PanelAxis::{p['axis']}, {p['gap']}, {p['padding']});")
        if kind == "Panel" and p["grid_columns"]:
            children = [child.name for child in self.widgets if child.parent == widget.name]
            if children:
                items = ", ".join(f"&widgets::{name}" for name in children)
                self.data.append(f"static BaseComponent* const {tag}_grid[] = {{{items}}};")
                self.layout.append(f"panelGrid({tag}_grid, {len(children)}, {p['grid_columns']}, "
                                   f"{{0, 0, {obj}.getSize().dx, {obj}.getSize().dy}}, "
                                   f"{cpp(p['grid_gap'])});")
        if kind == "Picture" and image:
            mask = f", {image.name}_mask" if image.mask else ""
            self.setup.append(f"{obj}.setSource({image.name}, {image.width}, {image.height}, true{mask});")
        if kind == "Pixmap" and image:
            mask = f", 1.0f, 0, 0, -1, -1, {image.name}_mask" if image.mask else ""
            self.setup.append(f"{obj}.pixmap.blitFromArray({image.name}, {image.width}, "
                              f"{image.height}, BlitMode::{p['mode']}, ScaleMode::{p['filter']}{mask});")
        if kind == "Sprite":
            pose = p["pose"]
            x, y = (cpp(float(pose.get(axis, length / 2))) for axis, length in
                    zip(("x", "y"), (widget.width, widget.height)))
            region = p["region"] or [0, 0, image.width if image else 1, image.height if image else 1]
            self.setup.extend(["{", f"    BlitTransform pose({x}, {y});",
                               f"    pose.pivotX = {cpp(float(pose.get('pivotX', region[2] / 2)))};",
                               f"    pose.pivotY = {cpp(float(pose.get('pivotY', region[3] / 2)))};"])
            for field in ("angle", "scaleX", "scaleY"):
                if field in pose:
                    self.setup.append(f"    pose.{field} = {cpp(float(pose[field]))};")
            self.setup.extend([f"    {obj}.setPose(pose);", "}"])
        if kind == "Plot":
            for sample in p["samples"]:
                self.setup.append(f"{obj}.append({cpp(float(sample))});")
            if p["demo_signal"]:
                self.frame.extend([f"static unsigned long {tag}_last = 0;",
                    f"static float {tag}_phase = 0;",
                    f"if (millis() - {tag}_last >= {p['interval_ms']}UL)",
                    "{", f"    {tag}_last = millis();",
                    f"    {tag}_phase = fmodf({tag}_phase + 0.15f, 6.2831853f);",
                    f"    {obj}.append(sinf({tag}_phase));", "}"])
        for name, field in schema.fields.items():
            value = p[name]
            if not field.method or (kind == "Tabs" and name == "selected"):
                continue
            if field.kind == "colors":
                if not value:
                    continue
                args = ", ".join(map(rgb, value))
            elif field.kind == "color":
                args = rgb(value)
            elif field.kind == "date":
                args = "{" + cpp(value) + "}"
            elif field.method == "setMode":
                args = "BlitMode::" + value
            else:
                args = cpp(value)
            if kind == "Window" and name in ("fit_single_child", "minimized", "maximized", "modal"):
                if value:
                    self.windows.append(f"{obj}.{field.method}({args});")
            else:
                self.setup.append(f"{obj}.{field.method}({args});")

    def render(self):
        self.add_widgets()
        header = [
            GENERATED.rstrip(), "#pragma once", "#include <PanelKit.h>", "",
            "namespace panelkit_ui {", f"extern {self.root_type} screen;",
            "extern TouchProcessor touch;", "namespace widgets {", *self.declarations,
            "}", "void configure();", "void update();",
            "template<class Display> bool present(Display& display, bool force = false)",
            "{", "    return screen.present(display, force);", "}", "}", "",
        ]
        source = [
            GENERATED.rstrip(), f'#include "{HEADER}"', f'#include "{FONT}"',
            f'#include "{ASSETS}"', self.project.includes, "",
            "namespace panelkit_ui {", f"{self.root_type} screen;",
            f"TouchProcessor touch(true, {self.project.drag_threshold}, "
            f"{self.project.double_click_ms}, {cpp(self.project.deferred_clicks)});",
            *[line for line in self.data if line.startswith("static Pixmap<")],
            "namespace widgets {", *self.definitions, "}", "",
            *[line for line in self.data if not line.startswith("static Pixmap<")], "",
            *self.callbacks, "", "void configure()", "{",
            "    static bool configured = false;", "    if (configured) return;",
            "    configured = true;",
            block(self.setup + self.tabs + self.windows + self.layout
                  + self.project.configure_cpp.splitlines()),
            "}", "", "void update()", "{",
            block(self.frame + self.project.frame_cpp.splitlines()), "}", "}", "",
        ]
        images = [GENERATED.rstrip(), "#pragma once", "#include <Arduino.h>", ""]
        for raster in self.rasters.values():
            images.extend(raster.code())
        return {HEADER: "\n".join(header), SOURCE: "\n".join(source),
                ASSETS: "\n".join(images) + "\n"}


def starter(project):
    pins = ", ".join(map(str, project.pins))
    return f"""#include <TeensyTFT.h>
#include "{HEADER}"

TeensyTFT display({pins});
bool displayReady = false;

void setup()
{{
    Serial.begin(115200);
    displayReady = display.begin();
    if (!displayReady) return;
    panelkit_ui::configure();
    panelkit_ui::present(display);
}}

void loop()
{{
    if (!displayReady) return;
    const bool touched = display.touched();
    panelkit_ui::touch.process(touched, display.touchX(), display.touchY());
    const int ch = Serial.read();
    if (ch >= 0) type(char(ch));
    panelkit_ui::update();
    panelkit_ui::present(display);
}}
"""


def export_project(project, target, *, create_sketch=True):
    """Export generated sources. An existing sketch is never rewritten."""
    target = Path(target).resolve()
    sketch = target / (target.name + ".ino")
    if create_sketch and not sketch.exists():
        check(not (target.is_dir() and any(target.glob("*.ino"))),
              "For an existing sketch, export in integration mode.")
        check(re.fullmatch(r"[A-Za-z0-9_][A-Za-z0-9_.-]{0,62}", target.name),
              "Choose an Arduino sketch folder name using letters, digits, _, . or -.")
    exporter = Exporter(project)
    outputs = exporter.render()
    assets = files("panelkit_designer").joinpath("assets")
    outputs[FONT] = (project.asset(project.font_header).read_text(encoding="utf-8-sig")
                     if project.font_header else
                     assets.joinpath("font_inter_regular_16.h").read_text(encoding="utf-8"))
    if not project.font_header:
        outputs["PanelKitFont-OFL.txt"] = assets.joinpath("OFL-Inter.txt").read_text(encoding="utf-8")
        license_path = target / "PanelKitFont-OFL.txt"
        check(not license_path.exists() or
              license_path.read_text(encoding="utf-8-sig") == outputs["PanelKitFont-OFL.txt"],
              "Export would replace a user file: PanelKitFont-OFL.txt.")
    if create_sketch and not sketch.exists():
        outputs[sketch.name] = starter(project)
    for name in (HEADER, SOURCE, ASSETS, FONT):
        dst = target / name
        if dst.exists():
            with dst.open(encoding="utf-8-sig") as stream:
                first = stream.readline()
            check(first == GENERATED, f"Export would replace a user file: {dst.name}.")
    outputs[FONT] = GENERATED + outputs[FONT]
    target.mkdir(parents=True, exist_ok=True)
    for name, content in outputs.items():
        atomic_text(target / name, content)
    return tuple(target / name for name in outputs)

